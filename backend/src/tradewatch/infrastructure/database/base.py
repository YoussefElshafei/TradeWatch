"""Declarative base, shared column types, and mixins.

Two things are set up here that are tedious to retrofit:

**A naming convention for constraints.** Without it PostgreSQL invents names like
``trades_instrument_id_fkey`` and, worse, unnamed CHECK constraints get names that differ
between a freshly created database and a migrated one — which makes Alembic autogenerate
produce spurious drops and recreations forever. With it, every constraint has a
deterministic name, an `IntegrityError` says which rule was broken, and a migration can
drop a constraint by name.

**A type annotation map.** ``Decimal`` always means ``NUMERIC(18, 8)`` and ``datetime``
always means ``TIMESTAMPTZ``. Those are ADR-0009 and `ARCHITECTURE.md` §4.4 expressed once,
rather than in every column definition where one of them can be forgotten.
"""

from __future__ import annotations

import datetime as dt
import uuid
from decimal import Decimal
from typing import Annotated, Any, ClassVar

from sqlalchemy import DateTime, MetaData, Numeric, String, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from tradewatch.domain.ids import new_id

# Money and quantity precision. 18 total digits with 8 after the point holds a price of
# 9,999,999,999.99999999 — far beyond any equity, and enough decimal places that crypto
# (decision D2) would not need a migration. ADR-0009.
MONEY_PRECISION = 18
MONEY_SCALE = 8

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

metadata = MetaData(naming_convention=NAMING_CONVENTION)


# --- Column type aliases ---------------------------------------------------
# Used as annotations: `price: Mapped[Money]`. They carry the type and nothing else, so a
# column keeps its own nullability and constraints.

Money = Annotated[Decimal, mapped_column(Numeric(MONEY_PRECISION, MONEY_SCALE))]
Timestamp = Annotated[dt.datetime, mapped_column(DateTime(timezone=True))]
Json = Annotated[dict[str, Any], mapped_column(JSONB)]
Symbol = Annotated[str, mapped_column(String(32))]
ShortText = Annotated[str, mapped_column(String(100))]


class Base(DeclarativeBase):
    """Declarative base for every ORM model."""

    metadata = metadata

    type_annotation_map: ClassVar[dict[Any, Any]] = {
        Decimal: Numeric(MONEY_PRECISION, MONEY_SCALE),
        dt.datetime: DateTime(timezone=True),
        uuid.UUID: PGUUID(as_uuid=True),
        dict[str, Any]: JSONB,
    }

    def __repr__(self) -> str:
        """Identify the row without dumping its contents into a log line."""
        keys = [column.name for column in self.__table__.primary_key]
        identity = ", ".join(f"{key}={getattr(self, key, None)!r}" for key in keys)
        return f"<{type(self).__name__} {identity}>"


class UUIDPrimaryKey:
    """A UUIDv7 primary key, generated by the application rather than the database.

    Client-side generation means an object knows its own id before the transaction
    commits, so a graph of related rows can be built in memory and inserted in one
    flush — and an event can carry the id of a row that is not yet visible to other
    sessions. UUIDv7 keeps the values time-ordered, so inserts still land at the right-hand
    edge of the index (see `tradewatch.domain.ids`).
    """

    id: Mapped[uuid.UUID] = mapped_column(PGUUID(as_uuid=True), primary_key=True, default=new_id)


class TimestampedMixin:
    """``created_at`` / ``updated_at``, maintained by the database clock.

    ``server_default`` rather than a Python default: one clock, and rows written by a
    migration or by psql get the same treatment as rows written by the application.
    """

    created_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
